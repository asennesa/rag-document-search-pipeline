"""Local UI over the pipeline services. Run: uv run streamlit run app/streamlit_app.py

Text from documents and from the model is untrusted, so it is only ever shown with plain
text elements. Nothing here renders it as Markdown or HTML.
"""

import streamlit as st

from rag_pipeline import app_services
from rag_pipeline.config import Settings
from rag_pipeline.errors import PipelineError
from rag_pipeline.models import RagResponse, RetrievedPassage, SearchResponse

ALL_SOURCES = "All documents"
STATUS_NOTES = {
    "answered": "Citation IDs are valid. That shows the sources exist, not that it is true.",
    "insufficient_evidence": "The model reported that the documents do not answer this.",
    "no_context": "No usable passages were found, so the model was not called.",
    "citation_invalid": "This answer failed citation checks. Do not treat it as grounded.",
}


@st.cache_resource(show_spinner=False)
def get_facade(settings_key: str) -> app_services.PipelineFacade:
    """Shared across sessions, holding models and clients only, never questions."""
    return app_services.create_facade(Settings())


def describe_page(page_number: int | None) -> str:
    return f", page {page_number}" if page_number else ""


def show_passage(passage: RetrievedPassage, rank: int) -> None:
    with st.container(border=True):
        st.text(
            f"{rank}. {passage.source}{describe_page(passage.page_number)}, "
            f"chunk {passage.chunk_index}"
        )
        st.text(f"Score: {passage.score:.4f}")
        st.code(passage.text, language=None, wrap_lines=True)


def available_sources(facade: app_services.PipelineFacade) -> list[str]:
    try:
        return facade.sources()
    except PipelineError:
        return []  # The tab that needs Qdrant reports the outage.


def request_controls(facade, settings: Settings, key: str) -> tuple[str, int, str | None, bool]:
    with st.form(f"{key}_form"):
        question = st.text_input("Question", key=f"{key}_question")
        left, right = st.columns(2)
        top_k = left.slider(
            "Passages to retrieve",
            1,
            settings.search_max_top_k,
            settings.search_top_k,
            key=f"{key}_top_k",
        )
        choice = right.selectbox(
            "Document filter",
            [ALL_SOURCES, *available_sources(facade)],
            key=f"{key}_source",
        )
        submitted = st.form_submit_button("Run", type="primary")
    return question, top_k, None if choice == ALL_SOURCES else choice, submitted


def search_section(facade, settings: Settings) -> None:
    st.write("Finds matching passages. This does not need Ollama.")
    question, top_k, source, submitted = request_controls(facade, settings, "search")
    if submitted:
        st.session_state.pop("search_response", None)
        try:
            with st.spinner("Searching"):
                st.session_state["search_response"] = facade.search(question, top_k, source)
        except PipelineError as error:
            st.error(str(error))
    response: SearchResponse | None = st.session_state.get("search_response")
    if response is None:
        return
    st.caption(
        f"Retrieval {response.retrieval_time_ms:.1f} ms "
        f"(embedding {response.embedding_time_ms:.1f} ms, "
        f"vector query {response.vector_query_time_ms:.1f} ms). "
        "Scores rank passages for this question; they are not confidence."
    )
    if not response.results:
        st.info("No matching passages.")
    for rank, passage in enumerate(response.results, start=1):
        show_passage(passage, rank)


def show_answer(response: RagResponse) -> None:
    st.subheader("Generated answer")
    with st.container(border=True):
        note = STATUS_NOTES.get(response.status, response.message or "")
        if response.status == "answered":
            st.success(note)
        elif response.status == "insufficient_evidence":
            st.info(note)
        else:
            st.warning(f"{response.status}: {note}")
        if response.answer:
            st.text(response.answer)
        cited = set(response.citation.cited_ids) if response.citation else set()
        if response.status == "answered":
            for source in response.sources:
                if source.source_id in cited:
                    page = describe_page(source.passage.page_number)
                    st.text(f"[{source.source_id}] {source.passage.source}{page}")
    st.caption(
        f"Retrieval {response.retrieval_time_ms:.1f} ms, "
        f"LLM generation {response.generation_time_ms:.1f} ms, "
        f"total {response.total_time_ms:.1f} ms."
    )
    st.subheader("Retrieved passages")
    st.caption("Source data from your documents, not generated by the model.")
    for rank, passage in enumerate(response.retrieved, start=1):
        with st.expander(f"Passage {rank} (score {passage.score:.4f})"):
            show_passage(passage, rank)


def rag_section(facade, settings: Settings) -> None:
    st.write("Answers from retrieved passages using the local Ollama model.")
    question, top_k, source, submitted = request_controls(facade, settings, "rag")
    if submitted:
        st.session_state.pop("rag_response", None)
        try:
            with st.spinner("Generating"):
                st.session_state["rag_response"] = facade.ask(question, top_k, source)
        except PipelineError as error:
            st.error(str(error))
    response: RagResponse | None = st.session_state.get("rag_response")
    if response is not None:
        show_answer(response)


def show_report(report) -> None:
    results = report.results
    counts = [result.status for result in results]
    st.text(
        f"Synced {counts.count('synced')}, unchanged {counts.count('unchanged')}, "
        f"cleaned {counts.count('cleaned')}, failed {counts.count('failed')}. "
        f"Vectors upserted {sum(result.upserted for result in results)}, "
        f"obsolete deleted {sum(result.deleted for result in results)}."
    )
    for failure in report.preparation.failures:
        st.text(f"Failed: {failure.source}: {failure.message}")
    for result in report.failed_results:
        st.text(f"Failed: {result.source}: {result.message}")
    for source in report.stale_sources:
        st.text(f"Stale: {source}: the previous revision stays searchable.")
    for source in report.missing_sources:
        st.text(f"Missing: {source}: the file is gone but stays indexed.")


def ingestion_controls(facade, settings: Settings) -> None:
    st.subheader("Add documents")
    if st.button("Ingest sample documents"):
        try:
            with st.spinner("Ingesting"):
                report = facade.ingest_samples()
        except PipelineError as error:
            st.error(str(error))
        else:
            if report.has_failures:
                st.warning("Ingestion finished with failures.")
            else:
                st.success("Sample ingestion finished.")
            show_report(report)

    limit_mb = settings.upload_max_bytes // (1024 * 1024)
    upload = st.file_uploader(
        f"Upload a PDF, Markdown, or TXT file (up to {limit_mb} MB; no OCR)",
        type=["pdf", "md", "txt"],
    )
    if upload is not None and st.button("Ingest uploaded file"):
        try:
            with st.spinner("Ingesting"):
                result = facade.ingest_upload(upload.name, upload.getvalue())
        except PipelineError as error:
            st.error(str(error))
        else:
            if result.status == "failed":
                st.warning("The upload was not ingested.")
            else:
                st.success("Upload ingested.")
                st.text(f"{result.source}: {result.status}, {result.chunk_count} chunks")
            show_report(result.report)


def inspection_section(facade, settings: Settings) -> None:
    ingestion_controls(facade, settings)
    st.subheader("Pipeline state")
    try:
        overview = facade.overview()
    except PipelineError as error:
        st.error(str(error))
        return
    if not overview.collection_exists:
        st.info("The collection does not exist yet. Ingest the sample documents to create it.")
        return
    stats = overview.stats
    first, second, third = st.columns(3)
    first.metric("Documents", overview.document_count)
    second.metric("Uploaded documents", overview.uploaded_document_count)
    third.metric("Chunks", stats.exact_points)
    st.table(
        {
            "Setting": [
                "Collection",
                "Status",
                "Optimizer status",
                "Embedding model",
                "Vector dimensions",
                "Distance metric",
                "Indexed vectors",
                "Segments",
                "HNSW m",
                "HNSW ef_construct",
                "Query hnsw_ef",
                "Full scan threshold (KB)",
                "Indexing threshold (KB)",
            ],
            "Value": [
                str(value)
                for value in (
                    stats.name,
                    stats.status,
                    stats.optimizer_status,
                    overview.embedding_model,
                    stats.dimensions,
                    stats.distance,
                    "not reported" if stats.indexed_vectors is None else stats.indexed_vectors,
                    "not reported" if stats.segments is None else stats.segments,
                    stats.hnsw_m,
                    stats.hnsw_ef_construct,
                    overview.hnsw_ef,
                    stats.full_scan_threshold_kb,
                    stats.indexing_threshold_kb,
                )
            ],
        }
    )
    st.info(overview.interpretation)


def main() -> None:
    st.set_page_config(page_title="RAG Document Search", layout="wide")
    st.title("RAG Document Search")
    st.caption("Local document search and question answering. Sample policies are fictional.")
    try:
        settings = Settings()
    except ValueError:
        st.error("Configuration is invalid. Check your .env file against .env.example.")
        return
    facade = get_facade(settings.model_dump_json())
    search_tab, rag_tab, inspection_tab = st.tabs(
        ["Semantic Search", "RAG Assistant", "Pipeline Inspection"]
    )
    with search_tab:
        search_section(facade, settings)
    with rag_tab:
        rag_section(facade, settings)
    with inspection_tab:
        inspection_section(facade, settings)


main()
